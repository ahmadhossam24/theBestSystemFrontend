import { tableToAoa, uniqueSheetName, nameSheets, safeFileName, stampForFile } from "./data/xlsxExport.js";
let pass = 0, fail = 0; const ok = (n, c, x) => { c ? pass++ : (fail++, console.log("FAIL", n, x ?? "")); };
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const cols = [{ label: "Name", key: "name" }, { label: "Phone", key: "p" }];
const get = (r, c) => r[c.key];
ok("header + rows", eq(tableToAoa(cols, [{ name: "A", p: "0100" }], get), [["Name", "Phone"], ["A", "0100"]]));
ok("leading zeros kept as text", tableToAoa(cols, [{ name: "A", p: "01001234567" }], get)[1][1] === "01001234567");
ok("long numbers keep every digit", tableToAoa(cols, [{ name: "A", p: 12345678901234567890n }], get)[1][1] === "12345678901234567890");
ok("null/undefined -> empty", eq(tableToAoa(cols, [{ name: null }], get)[1], ["", ""]));
ok("no rows -> header only", eq(tableToAoa(cols, [], get), [["Name", "Phone"]]));
ok("sheet name max 31", uniqueSheetName("x".repeat(50), new Set()).length === 31);
ok("illegal chars removed", !/[\[\]:*?/\\]/.test(uniqueSheetName("a[b]:c*d?e/f\\g", new Set())));
ok("empty name", uniqueSheetName("", new Set()) === "Sheet");
ok("unique, case-insensitive", uniqueSheetName("Sales", new Set(["sales"])) === "Sales (2)");
ok("unique when truncated", (() => { const long = "y".repeat(40); const a = uniqueSheetName(long, new Set()); const b = uniqueSheetName(long, new Set([a])); return a !== b && b.length <= 31; })());
ok("nameSheets dedups a list", eq(nameSheets([{ name: "A" }, { name: "a" }, { name: "A" }]).map((s) => s.name), ["A", "a (2)", "A (3)"]));
ok("apostrophe edges stripped", !uniqueSheetName("'x'", new Set()).startsWith("'"));
ok("file name safe", safeFileName("Sales A/../x?") === "Sales-A..x" || /^[\p{L}\p{N}._-]+$/u.test(safeFileName("Sales A/../x?")), safeFileName("Sales A/../x?"));
ok("file name never empty", safeFileName("///") === "export");
ok("stamp", stampForFile(new Date(2026, 0, 5)) === "2026-01-05");
console.log(`${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
